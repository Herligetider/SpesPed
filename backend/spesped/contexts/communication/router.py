router=APIRouter(prefix='/api/v1/schools/{school_id}/communication',tags=['communication'])
def communication_db(request:Request,db:Session=Depends(documents_db),actor:Actor=Depends(get_actor)):
    db.info['communication_transport_registry']=getattr(request.app.state,'communication_transport_registry',None)
    db.info['communication_session_id']=request.state.login_session.id
    return db
D=Depends(communication_db);A=Depends(get_actor)
